#!/usr/bin/env python3
"""Give a bb-generated UltraHonk verifier a unique top-level contract name.

bb emits `contract HonkVerifier` plus file-level constants/libraries with fixed
names. Only the deployable contract is renamed; files are never imported together
(contracts and tests deploy verifiers by artifact path), so the shared helper
names don't collide.
"""
import sys

path, prefix = sys.argv[1], sys.argv[2]
src = open(path).read()
needle = "contract HonkVerifier is"
assert src.count(needle) == 1, "unexpected verifier layout; check bb version"
src = src.replace(needle, f"contract {prefix}Verifier is")
header = (
    f"// AUTO-GENERATED by zk/scripts/build-circuits.sh from circuit `{prefix}`\n"
    "// (bb 5.2.1 write_solidity_verifier -t evm). DO NOT EDIT; rebuild instead.\n"
)
sys.stdout.write(header + src)
