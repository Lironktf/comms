#!/usr/bin/env node
// Writes zk/client/src/abi.ts from Foundry artifacts (run after `forge build`).
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";
const ZK = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(ZK, "contracts", "out");
const items = {
  shieldedPoolAbi: "ShieldedPool.sol/ShieldedPool.json",
  paymentBookAbi: "PaymentBook.sol/PaymentBook.json",
  vendorTreeAbi: "VendorTree.sol/VendorTree.json",
  associationSetAbi: "AssociationSetRegistry.sol/AssociationSetRegistry.json",
  mockUsdcAbi: "MockUSDC.sol/MockUSDC.json",
  mockSwapRouterAbi: "MockSwapRouter.sol/MockSwapRouter.json",
  vendorRegistryAbi: "VendorRegistry.sol/VendorRegistry.json",
  attestationRegistryAbi: "AttestationRegistry.sol/AttestationRegistry.json",
};
let src = "// AUTO-GENERATED by zk/scripts/gen-abi.mjs from Foundry artifacts. Do not edit.\n";
for (const [name, file] of Object.entries(items)) {
  const abi = JSON.parse(readFileSync(join(out, file), "utf8")).abi;
  src += `export const ${name} = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(join(ZK, "client", "src", "abi.ts"), src);
console.log("wrote client/src/abi.ts");
